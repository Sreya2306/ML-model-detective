pressure_readings = [102.5, 98.0, 110.2, 95.5, 120.0]

print("All pressure readings:")
print(pressure_readings)

print("\nFirst pressure reading:")
print(pressure_readings[0])

print("\nNumber of readings:")
print(len(pressure_readings))

print("\nHighest pressure:")
print(max(pressure_readings))

print("\nLowest pressure:")
print(min(pressure_readings))

print("\nAverage pressure:")
print(sum(pressure_readings) / len(pressure_readings))